"""
Email Service Module

This module handles sending LinkedIn post drafts via email.

Why this file exists:
- Delivers generated posts to your inbox
- Formats emails professionally with HTML
- Handles SMTP connection and error handling
- Provides retry logic for reliability

How it works:
1. Takes a LinkedInPost object
2. Formats it into an HTML email
3. Connects to SMTP server (Gmail)
4. Sends email with the post draft
5. Handles errors gracefully

Email Format:
- Subject: AI News Post - [Article Title]
- Body: HTML formatted with post content and metadata
- Includes: Source article link, post stats, copy-paste ready text
"""

import smtplib
from email.mime.text import MIMEText
from email.mime.multipart import MIMEMultipart
from datetime import datetime
from typing import Optional

from models import LinkedInPost
from config import config
from utils import get_logger

logger = get_logger(__name__)


class EmailService:
    """
    Sends LinkedIn post drafts via email using SMTP.
    """

    def __init__(self):
        """Initialize the email service with configuration."""
        self.smtp_server = config.SMTP_SERVER
        self.smtp_port = config.SMTP_PORT
        self.sender_email = config.SENDER_EMAIL
        self.sender_password = config.SENDER_PASSWORD
        self.receiver_email = config.RECEIVER_EMAIL

        # Validate configuration
        if not all([self.sender_email, self.sender_password, self.receiver_email]):
            raise ValueError("Email configuration incomplete. Check .env file.")

    def send_post(self, post: LinkedInPost) -> bool:
        """
        Send a LinkedIn post draft via email.

        Args:
            post: LinkedInPost object to send

        Returns:
            True if sent successfully, False otherwise
        """
        logger.info(f"Sending email to {self.receiver_email}")

        try:
            # Create email message
            message = self._create_email_message(post)

            # Send via SMTP
            self._send_via_smtp(message)

            logger.info("Email sent successfully")
            return True

        except smtplib.SMTPAuthenticationError:
            logger.error("SMTP authentication failed. Check email credentials.")
            return False
        except smtplib.SMTPException as e:
            logger.error(f"SMTP error: {str(e)}")
            return False
        except Exception as e:
            logger.error(f"Failed to send email: {str(e)}", exc_info=True)
            return False

    def _create_email_message(self, post: LinkedInPost) -> MIMEMultipart:
        """
        Create a formatted email message.

        Args:
            post: LinkedInPost to format

        Returns:
            MIMEMultipart email message
        """
        # Create message container
        message = MIMEMultipart("alternative")
        message["Subject"] = f"AI News Post - {post.source_article.title[:50]}..."
        message["From"] = self.sender_email
        message["To"] = self.receiver_email

        # Create plain text version
        text_content = self._format_text_email(post)

        # Create HTML version
        html_content = self._format_html_email(post)

        # Attach both versions
        part1 = MIMEText(text_content, "plain")
        part2 = MIMEText(html_content, "html")

        message.attach(part1)
        message.attach(part2)

        return message

