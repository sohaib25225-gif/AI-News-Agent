    def _send_via_smtp(self, message: MIMEMultipart) -> None:
        """
        Send email via SMTP.

        Args:
            message: Email message to send

        Raises:
            Various SMTP exceptions on failure
        """
        logger.debug(f"Connecting to SMTP server: {self.smtp_server}:{self.smtp_port}")

        # Create SMTP connection
        with smtplib.SMTP(self.smtp_server, self.smtp_port) as server:
            server.set_debuglevel(0)  # Set to 1 for verbose SMTP debugging

            # Start TLS encryption
            server.starttls()
            logger.debug("TLS connection established")

            # Login
            server.login(self.sender_email, self.sender_password)
            logger.debug("SMTP authentication successful")

            # Send email
            server.send_message(message)
            logger.debug("Email sent via SMTP")

